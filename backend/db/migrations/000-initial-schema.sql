BEGIN;

CREATE TABLE brands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255)
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description varchar(255)
);

CREATE TABLE colors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255)
);

CREATE TABLE customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    phone varchar(255),
    total_purchases integer,
    created_at timestamp(6)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(255),
    username varchar(255) UNIQUE,
    password_hash varchar(255),
    role varchar(255) CHECK (role IN ('ADMIN', 'CASHIER')),
    active boolean,
    created_at timestamp(6)
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    description varchar(255),
    status boolean,
    created_at timestamp(6),
    category_id bigint REFERENCES categories (id),
    brand_id bigint REFERENCES brands (id)
);

CREATE TABLE product_variants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint REFERENCES products (id),
    color_id bigint REFERENCES colors (id),
    size integer,
    catalog_price numeric(38,2),
    stock integer,
    created_at timestamp(6)
);

CREATE TABLE sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint,
    customer_id bigint REFERENCES customers (id),
    customer_name varchar(255),
    total numeric(38,2),
    payment_type varchar(255) CHECK (payment_type IN ('CASH', 'YAPE_PLIN')),
    status varchar(255) CHECK (status IN ('COMPLETED', 'CANCELLED')),
    created_at timestamp(6)
);

CREATE TABLE sale_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint REFERENCES sales (id),
    variant_id bigint,
    unit_price numeric(38,2),
    quantity integer,
    subtotal numeric(38,2)
);

COMMIT;
